-- Таблица как объект схемы: восьмой тип элемента.
-- В прежней базе это было «украшение» вида matrix, из-за чего оно ничего
-- не значило и нигде не показывалось. Здесь у таблицы свой тип, а её
-- содержимое лежит в допе `table` понятной формой:
--   {"head": ["колонка", …], "rows": [{"name": "строка", "cells": ["…", …]}, …]}

ALTER TABLE elements
  MODIFY `type` ENUM('block','decision','gateway','arrow','group','area','note','table') NOT NULL;
